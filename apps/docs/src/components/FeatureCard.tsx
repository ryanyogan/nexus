import React, { type ReactNode } from 'react';

interface FeatureCardProps {
  icon: ReactNode;
  title: string;
  description: string;
  link?: string;
}

/**
 * Feature card component for highlighting capabilities
 */
export function FeatureCard({ icon, title, description, link }: FeatureCardProps) {
  const content = (
    <>
      <div className="feature-card__icon">{icon}</div>
      <h3 className="feature-card__title">{title}</h3>
      <p className="feature-card__description">{description}</p>
    </>
  );

  if (link) {
    return (
      <a href={link} className="feature-card" style={{ textDecoration: 'none' }}>
        {content}
      </a>
    );
  }

  return <div className="feature-card">{content}</div>;
}

interface FeatureGridProps {
  children: ReactNode;
}

/**
 * Grid container for feature cards
 */
export function FeatureGrid({ children }: FeatureGridProps) {
  return <div className="feature-grid">{children}</div>;
}

